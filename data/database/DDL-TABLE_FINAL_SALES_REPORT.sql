use etl_db
go

CREATE TABLE dbo.TABLE_FINAL_SALES_REPORT (
    -- Unique Identifier for each pipeline run
    ID INT IDENTITY(1,1) NOT NULL,

    -- Unique Identifier and Dates
    ORDER_ID NVARCHAR(50) NULL,
    ORDER_DATE DATE NULL,
    
    -- Customer Information
    CUSTOMER_ID NVARCHAR(50) NULL,
    CUSTOMER_NAME NVARCHAR(150) NULL,
    CUSTOMER_SEGMENT NVARCHAR(50),
    
    -- Product Information
    PRODUCT_ID NVARCHAR(50) NULL,
    PRODUCT_NAME NVARCHAR(255) NULL,
    CATEGORY NVARCHAR(100),
    BRAND NVARCHAR(100),
    
    -- Quantities and Prices
    QUANTITY INT NULL,
    UNIT_PRICE DECIMAL(18, 2) NULL,
    DISCOUNT DECIMAL(5, 2) DEFAULT 0.00, -- Percentage (e.g., 10.50 for 10.5%)
    
    -- Financial Breakdowns
    GROSS_AMOUNT DECIMAL(18, 2) NULL,
    DISCOUNT_AMOUNT DECIMAL(18, 2) DEFAULT 0.00,
    AMOUNT_AFTER_DISCOUNT DECIMAL(18, 2) NULL,
    GST_AMOUNT DECIMAL(18, 2) DEFAULT 0.00,
    FINAL_AMOUNT DECIMAL(18, 2) NULL,
    
    -- Metadata and Geography
    PAYMENT_METHOD NVARCHAR(50),
    CITY NVARCHAR(100),
    COUNTRY NVARCHAR(100),
    ORDER_VALUE_CATEGORY NVARCHAR(50),

    -- Audit Trail
    CREATED_AT DATETIME2 DEFAULT GETDATE(),
    UPDATED_AT DATETIME2 DEFAULT GETDATE(),
    CREATED_BY NVARCHAR(100) DEFAULT SYSTEM_USER,
    UPDATED_BY NVARCHAR(100) DEFAULT SYSTEM_USER,
);